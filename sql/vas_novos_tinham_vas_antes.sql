-- Dos clientes NOVO no produto filtrado: já tinham algum VAS no mês passado?
--
-- Parte dos clientes classificados como NOVO no SKEELO (VAL_MES_ANTERIOR = 0
-- nesse produto) pode já ter tido outro VAS em setembro. Esta consulta separa:
--   SEM_VAS_NO_MES_PASSADO     = cliente sem nenhum NT Receita/Bruta em set
--   JA_TINHA_VAS_NO_MES_PASSADO = cliente já tinha algum VAS em set
--
-- Antes de executar, ajuste datas e FILTRO_PRODUTO em PARAMETROS.

WITH PARAMETROS AS (
    SELECT
        DATE '2026-09-01' AS MES_ANTERIOR,
        DATE '2026-10-01' AS MES_ATUAL,
        'SKEELO AUDIOBOOK RED (V)' AS FILTRO_PRODUTO
    FROM DUAL
),
BASE AS (
    SELECT
        T.COD_OPERADORA,
        T.NUM_CONTRATO,
        T.DSC_PRODUTO,
        SUM(CASE WHEN T.DAT_COMPETENCIA = P.MES_ANTERIOR
                 THEN T.VAL_CALCULADO ELSE 0 END) AS VAL_MES_ANTERIOR,
        SUM(CASE WHEN T.DAT_COMPETENCIA = P.MES_ATUAL
                 THEN T.VAL_CALCULADO ELSE 0 END) AS VAL_MES_ATUAL
    FROM u92870757.BI_FP_RECEITA_FIXA T
    CROSS JOIN PARAMETROS P
    WHERE T.DSC_TIPO_PRODUTO = 'NT'
      AND T.DSC_TIPO = 'Receita'
      AND T.DSC_SUBTIPO = 'Bruta'
      AND T.DAT_COMPETENCIA IN (P.MES_ANTERIOR, P.MES_ATUAL)
    GROUP BY
        T.COD_OPERADORA,
        T.NUM_CONTRATO,
        T.DSC_PRODUTO
),
CLIENTES_COM_AUMENTO AS (
    SELECT
        COD_OPERADORA,
        NUM_CONTRATO
    FROM BASE
    GROUP BY
        COD_OPERADORA,
        NUM_CONTRATO
    HAVING SUM(VAL_MES_ATUAL) > SUM(VAL_MES_ANTERIOR)
),
CLIENTES_NOVOS_NO_PRODUTO AS (
    SELECT
        B.COD_OPERADORA,
        B.NUM_CONTRATO
    FROM BASE B
    JOIN CLIENTES_COM_AUMENTO C
      ON C.COD_OPERADORA = B.COD_OPERADORA
     AND C.NUM_CONTRATO = B.NUM_CONTRATO
    CROSS JOIN PARAMETROS P
    WHERE B.DSC_PRODUTO LIKE P.FILTRO_PRODUTO
      AND B.VAL_MES_ANTERIOR = 0
      AND B.VAL_MES_ATUAL > 0
),
POR_CLIENTE AS (
    SELECT
        N.COD_OPERADORA,
        N.NUM_CONTRATO,
        SUM(B.VAL_MES_ANTERIOR) AS VAS_MES_PASSADO,
        SUM(CASE WHEN B.DSC_PRODUTO LIKE P.FILTRO_PRODUTO
                 THEN B.VAL_MES_ATUAL ELSE 0 END) AS PRODUTO_MES_ATUAL
    FROM CLIENTES_NOVOS_NO_PRODUTO N
    JOIN BASE B
      ON B.COD_OPERADORA = N.COD_OPERADORA
     AND B.NUM_CONTRATO = N.NUM_CONTRATO
    CROSS JOIN PARAMETROS P
    GROUP BY
        N.COD_OPERADORA,
        N.NUM_CONTRATO
)
SELECT *
FROM (
    SELECT
        CASE
            WHEN VAS_MES_PASSADO = 0 THEN 'SEM_VAS_NO_MES_PASSADO'
            ELSE 'JA_TINHA_VAS_NO_MES_PASSADO'
        END AS SITUACAO_MES_PASSADO,
        COUNT(*) AS QTD_CLIENTES,
        ROUND(SUM(VAS_MES_PASSADO), 2) AS VAS_MES_PASSADO,
        ROUND(SUM(PRODUTO_MES_ATUAL), 2) AS PRODUTO_MES_ATUAL
    FROM POR_CLIENTE
    GROUP BY
        CASE
            WHEN VAS_MES_PASSADO = 0 THEN 'SEM_VAS_NO_MES_PASSADO'
            ELSE 'JA_TINHA_VAS_NO_MES_PASSADO'
        END
) R
ORDER BY R.QTD_CLIENTES DESC
