-- Resumo dos clientes por trás da variação de um produto de VAS.
--
-- Mesmos critérios de vas_clientes_do_produto.sql. Em vez da lista de
-- clientes, agrupa por TIPO_CONTRIBUICAO para responder rápido: quanto do
-- ~1,5 mi veio de cliente novo, quanto de aumento real e quanto de estorno.

WITH PARAMETROS AS (
    SELECT
        DATE '2026-09-01' AS MES_ANTERIOR,
        DATE '2026-10-01' AS MES_ATUAL,
        'SKEELO AUDIOBOOK RED (V)' AS FILTRO_PRODUTO
    FROM DUAL
),
BASE AS (
    SELECT
        T.COD_OPERADORA,
        T.NUM_CONTRATO,
        T.DSC_PRODUTO,
        SUM(CASE WHEN T.DAT_COMPETENCIA = P.MES_ANTERIOR
                 THEN T.VAL_CALCULADO ELSE 0 END) AS VAL_MES_ANTERIOR,
        SUM(CASE WHEN T.DAT_COMPETENCIA = P.MES_ATUAL
                 THEN T.VAL_CALCULADO ELSE 0 END) AS VAL_MES_ATUAL
    FROM u92870757.BI_FP_RECEITA_FIXA T
    CROSS JOIN PARAMETROS P
    WHERE T.DSC_TIPO_PRODUTO = 'NT'
      AND T.DSC_TIPO = 'Receita'
      AND T.DSC_SUBTIPO = 'Bruta'
      AND T.DAT_COMPETENCIA IN (P.MES_ANTERIOR, P.MES_ATUAL)
    GROUP BY
        T.COD_OPERADORA,
        T.NUM_CONTRATO,
        T.DSC_PRODUTO
),
CLIENTES_COM_AUMENTO AS (
    SELECT
        COD_OPERADORA,
        NUM_CONTRATO
    FROM BASE
    GROUP BY
        COD_OPERADORA,
        NUM_CONTRATO
    HAVING SUM(VAL_MES_ATUAL) > SUM(VAL_MES_ANTERIOR)
),
POR_CLIENTE AS (
    SELECT
        B.COD_OPERADORA,
        B.NUM_CONTRATO,
        B.DSC_PRODUTO,
        B.VAL_MES_ANTERIOR,
        B.VAL_MES_ATUAL,
        B.VAL_MES_ATUAL - B.VAL_MES_ANTERIOR AS VARIACAO,
        CASE
            WHEN B.VAL_MES_ANTERIOR = 0 AND B.VAL_MES_ATUAL > 0 THEN 'NOVO'
            WHEN B.VAL_MES_ANTERIOR < 0 AND B.VAL_MES_ATUAL = 0 THEN 'ESTORNO'
            WHEN B.VAL_MES_ATUAL > B.VAL_MES_ANTERIOR THEN 'AUMENTO'
            WHEN B.VAL_MES_ATUAL < B.VAL_MES_ANTERIOR THEN 'QUEDA'
            ELSE 'SEM_VARIACAO'
        END AS TIPO_CONTRIBUICAO
    FROM BASE B
    JOIN CLIENTES_COM_AUMENTO C
      ON C.COD_OPERADORA = B.COD_OPERADORA
     AND C.NUM_CONTRATO = B.NUM_CONTRATO
    CROSS JOIN PARAMETROS P
    WHERE B.DSC_PRODUTO LIKE P.FILTRO_PRODUTO
      AND B.VAL_MES_ATUAL <> B.VAL_MES_ANTERIOR
)
SELECT *
FROM (
    SELECT
        DSC_PRODUTO,
        TIPO_CONTRIBUICAO,
        COUNT(*) AS QTD_CLIENTES,
        ROUND(SUM(VAL_MES_ANTERIOR), 2) AS VAL_MES_ANTERIOR,
        ROUND(SUM(VAL_MES_ATUAL), 2) AS VAL_MES_ATUAL,
        ROUND(SUM(VARIACAO), 2) AS VARIACAO
    FROM POR_CLIENTE
    GROUP BY
        DSC_PRODUTO,
        TIPO_CONTRIBUICAO
) R
-- ABS(SUM(VARIACAO)) no ORDER BY dá ORA-00935 no Oracle: o alias
-- VARIACAO já tem SUM, e o banco aninha as duas funções.
ORDER BY ABS(R.VARIACAO) DESC
