-- Dois movimentos de NT (Receita/Bruta e Desconto/Bruta) por segmento.
--
-- CLARO FIBRA via de-para. CONS e CONSUMO são tratados como o mesmo
-- segmento (CONSUMO). Ajuste as datas em PARAMETROS.

WITH PARAMETROS AS (
    SELECT
        DATE '2026-09-01' AS MES_ANTERIOR,
        DATE '2026-10-01' AS MES_ATUAL,
        'CLARO FIBRA' AS FILTRO_PRODUTO_COGNOS
    FROM DUAL
)
SELECT *
FROM (
    SELECT
        CASE
            WHEN T.DSC_SEGMENTACAO IN ('CONS', 'CONSUMO') THEN 'CONSUMO'
            ELSE T.DSC_SEGMENTACAO
        END AS DSC_SEGMENTACAO,
        T.DSC_TIPO,
        T.DSC_SUBTIPO,
        ROUND(SUM(CASE WHEN T.DAT_COMPETENCIA = P.MES_ANTERIOR
                       THEN T.VAL_CALCULADO ELSE 0 END), 2) AS VAL_MES_ANTERIOR,
        ROUND(SUM(CASE WHEN T.DAT_COMPETENCIA = P.MES_ATUAL
                       THEN T.VAL_CALCULADO ELSE 0 END), 2) AS VAL_MES_ATUAL,
        ROUND(SUM(CASE WHEN T.DAT_COMPETENCIA = P.MES_ATUAL
                       THEN T.VAL_CALCULADO ELSE -T.VAL_CALCULADO END), 2) AS VARIACAO
    FROM u92870757.BI_FP_RECEITA_FIXA T
    JOIN N5919189.BI_DIM_CONTACONTABIL_FIXA D
      ON TRIM(TO_CHAR(D.CONTA_CONTABIL)) = TRIM(TO_CHAR(T.COD_CONTA_CONTABIL))
    CROSS JOIN PARAMETROS P
    WHERE T.DSC_TIPO_PRODUTO = 'NT'
      AND T.DSC_TIPO IN ('Receita', 'Desconto')
      AND T.DSC_SUBTIPO = 'Bruta'
      AND T.DAT_COMPETENCIA IN (P.MES_ANTERIOR, P.MES_ATUAL)
      AND D.PRODUTO_COGNOS = P.FILTRO_PRODUTO_COGNOS
    GROUP BY
        CASE
            WHEN T.DSC_SEGMENTACAO IN ('CONS', 'CONSUMO') THEN 'CONSUMO'
            ELSE T.DSC_SEGMENTACAO
        END,
        T.DSC_TIPO,
        T.DSC_SUBTIPO
) R
ORDER BY
    R.DSC_SEGMENTACAO,
    R.DSC_TIPO
